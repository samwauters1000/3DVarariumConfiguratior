// Pre-renders the catalogue thumbnails (plants, decoration, animals) into static WebP files,
// so phones and tablets show the same 3D previews as desktop without rendering them live.
//
//   npm run thumbnails
//
// Starts a Vite dev server, opens the app in headless Chrome, renders every item with the
// app's own thumbnail renderer and writes:
// - public/thumbnails/<category>/<item id>.webp
// - src/data/thumbnails.generated.js (which items have a file, plus a version for caching)
//
// Run it again after changing or adding models. Chrome is found at the usual install path,
// or set CHROME_PATH.

import { spawn } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { createServer } from 'vite'

const root = resolve(import.meta.dirname, '..')
const outDir = join(root, 'public', 'thumbnails')
const manifestFile = join(root, 'src', 'data', 'thumbnails.generated.js')
const DEV_PORT = 5199
const DEBUG_PORT = 9335

const chromeCandidates = [
  process.env.CHROME_PATH,
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].filter(Boolean)
const chromePath = chromeCandidates.find((path) => existsSync(path))
if (!chromePath) {
  console.error('Chrome was not found. Set CHROME_PATH to your Chrome or Chromium executable.')
  process.exit(1)
}

const wait = (ms) => new Promise((done) => setTimeout(done, ms))

const server = await createServer({ root, server: { port: DEV_PORT, strictPort: true }, logLevel: 'error' })
await server.listen()

const profile = mkdtempSync(join(tmpdir(), 'vararium-thumbs-'))
const chrome = spawn(
  chromePath,
  ['--headless=new', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', `--remote-debugging-port=${DEBUG_PORT}`, `--user-data-dir=${profile}`, 'about:blank'],
  { stdio: 'ignore' },
)

try {
  let targets = null
  for (let attempt = 0; attempt < 50 && !targets; attempt++) {
    try {
      targets = await (await fetch(`http://127.0.0.1:${DEBUG_PORT}/json`)).json()
    } catch {
      await wait(200)
    }
  }
  const page = targets.find((target) => target.type === 'page')
  const socket = new WebSocket(page.webSocketDebuggerUrl)
  await new Promise((done) => socket.addEventListener('open', done))
  let nextId = 0
  const pending = new Map()
  socket.addEventListener('message', (event) => {
    const message = JSON.parse(event.data)
    if (pending.has(message.id)) {
      pending.get(message.id)(message)
      pending.delete(message.id)
    }
  })
  const send = (method, params = {}) =>
    new Promise((done) => {
      const id = ++nextId
      pending.set(id, done)
      socket.send(JSON.stringify({ id, method, params }))
    })

  await send('Page.enable')
  await send('Page.navigate', { url: `http://localhost:${DEV_PORT}/` })
  await wait(4000)

  const result = await send('Runtime.evaluate', {
    awaitPromise: true,
    returnByValue: true,
    expression: `(async () => {
      const renderer = await import('/src/scene/thumbnails/thumbnailRenderer.jsx')
      const { placeableCategories } = await import('/src/data/objectCategories.js')
      const entries = Object.values(placeableCategories).flatMap((category) => category.items.map((item) => ({ categoryId: category.id, item })))
      return renderer.renderAllThumbnails(entries)
    })()`,
  })
  if (result.result?.exceptionDetails || !Array.isArray(result.result?.result?.value)) {
    throw new Error(`Rendering failed: ${JSON.stringify(result.result?.exceptionDetails ?? result.result).slice(0, 500)}`)
  }

  const images = result.result.result.value.filter((entry) => entry.dataUrl?.startsWith('data:image/webp'))
  rmSync(outDir, { recursive: true, force: true })
  for (const { categoryId, id, dataUrl } of images) {
    mkdirSync(join(outDir, categoryId), { recursive: true })
    writeFileSync(join(outDir, categoryId, `${id}.webp`), Buffer.from(dataUrl.split(',')[1], 'base64'))
  }

  const keys = images.map(({ categoryId, id }) => `${categoryId}:${id}`).sort()
  writeFileSync(
    manifestFile,
    `// Generated by \`npm run thumbnails\` (scripts/generate-thumbnails.mjs). Do not edit by hand.
// Catalogue items that have a pre-rendered thumbnail in public/thumbnails/<category>/<id>.webp.
export const THUMBNAIL_VERSION = '${Date.now().toString(36)}'

export const prerenderedThumbnails = new Set(${JSON.stringify(keys, null, 2)})
`,
  )
  console.log(`Wrote ${images.length} thumbnails to public/thumbnails and updated src/data/thumbnails.generated.js.`)
  socket.close()
} finally {
  chrome.kill()
  await server.close()
  await wait(300)
  rmSync(profile, { recursive: true, force: true })
}
